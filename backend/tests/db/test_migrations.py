import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Connection, inspect

pytestmark = pytest.mark.db

APP_TABLES = {"tenants", "users", "patients", "devices"}


def table_names(connection: Connection) -> set[str]:
    return set(inspect(connection).get_table_names())


def test_upgrade_applies_to_a_clean_database(empty_db: Connection, migrations: Config) -> None:
    command.upgrade(migrations, "head")

    assert table_names(empty_db) == APP_TABLES | {"alembic_version"}


def test_downgrade_rolls_back_cleanly_and_upgrade_works_again(
    empty_db: Connection, migrations: Config
) -> None:
    command.upgrade(migrations, "head")

    command.downgrade(migrations, "base")
    assert table_names(empty_db) == {"alembic_version"}

    command.upgrade(migrations, "head")
    assert table_names(empty_db) == APP_TABLES | {"alembic_version"}


def test_models_match_migrations(migrations: Config) -> None:
    """Fails if someone changes a model without adding a migration."""
    command.upgrade(migrations, "head")

    command.check(migrations)  # raises AutoGenerateDiffsDetected on any difference


def test_every_tenant_owned_table_has_an_indexed_tenant_fk(
    empty_db: Connection, migrations: Config
) -> None:
    command.upgrade(migrations, "head")
    inspector = inspect(empty_db)

    for table in APP_TABLES - {"tenants"}:
        fks = inspector.get_foreign_keys(table)
        assert any(
            fk["constrained_columns"] == ["tenant_id"] and fk["referred_table"] == "tenants"
            for fk in fks
        ), f"{table}.tenant_id has no FK to tenants"

        leading = [ix["column_names"][0] for ix in inspector.get_indexes(table)]
        leading += [uq["column_names"][0] for uq in inspector.get_unique_constraints(table)]
        assert "tenant_id" in leading, f"{table}.tenant_id is not indexed"
